def _write_coords(sim_dir, rot, nsnap=600, comment=True, spl=True):
    pot = sim_dir / "potential" / "10kpc"
    pot.mkdir(parents=True, exist_ok=True)
    body = "\n".join(" ".join(f"{v:.17g}" for v in row) for row in rot)
    head = "# generated by the FIRE pipeline\n1 2 3 4\n5 6 7 8\n"
    if comment:
        head += "# rotation to principal-axis frame\n"
    suffix = "_coords_spl.txt" if spl else "_coords.txt"
    (pot / f"{nsnap}{suffix}").write_text(head + body + "\n")
    return sim_dir


@pytest.mark.parametrize("comment", [True, False])
def test_read_rotation_ignores_the_optional_comment(tmp_path, rotation, comment):
    """m12m/m12f label the block; m12i/m12b do not. Both must work."""
    sim = _write_coords(tmp_path, rotation, comment=comment)
    assert np.allclose(read_rotation(sim, nsnap=600), rotation)


def test_read_rotation_spl_flag_picks_the_other_file(tmp_path, rotation):
    sim = _write_coords(tmp_path, rotation, spl=False)
    assert np.allclose(read_rotation(sim, nsnap=600, spl=False), rotation)
    with pytest.raises(FileNotFoundError):
        read_rotation(sim, nsnap=600, spl=True)


def test_read_rotation_rejects_a_short_file(tmp_path):
    pot = tmp_path / "potential" / "10kpc"
    pot.mkdir(parents=True)
    (pot / "600_coords_spl.txt").write_text("# only a comment\n1 2 3\n")
    with pytest.raises(ValueError, match="last three"):
        read_rotation(tmp_path, nsnap=600)


