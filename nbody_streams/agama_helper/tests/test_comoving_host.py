"""
test_comoving_host.py
~~~~~~~~~~~~~~~~~~~~~
Tests for the comoving-host helpers in ``agama_helper._fire``: the
principal-axis rotation, the centre-of-mass splines, and the galactic-centre
acceleration correction.

The centre term ``u_dot = a x_com'' + H a x_com'`` is the one piece of the
comoving equation of motion that does **not** cancel when changing variables to
physical coordinates, so it is worth pinning down exactly.

Covers
------
1. ``read_rotation`` takes the last three uncommented rows, with and without
   the ``# rotation to principal-axis frame`` comment that only half the FIRE
   suite writes.
2. ``write_center_splines`` / ``read_center_splines`` round-trip a BSpline
   exactly, including its derivatives -- the text form is what the acceleration
   is built from.
3. The acceleration table reproduces the closed-form ``-u_dot`` row by row,
   including the ``/K^2`` unit conversion that is wrong by 9.4 percent if
   multiplied instead.
4. Rotation, path-pattern input, ``t_range`` and ``n_samples`` behaviour.
5. ``center_acceleration`` and ``write_center_acceleration`` produce identical
   forces through agama, through the written ``.ini``, and (when CuPy is
   present) through ``PotentialGPU``.
"""

import numpy as np
import pytest

from nbody_streams.agama_helper import (
    center_acceleration,
    center_acceleration_table,
    read_center_splines,
    read_rotation,
    write_center_acceleration,
    write_center_splines,
)
from nbody_streams.utils import KPC_PER_GYR_PER_KMS, FlatLCDM

agama = pytest.importorskip("agama")
make_interp_spline = pytest.importorskip("scipy.interpolate").make_interp_spline

COSMO = FlatLCDM()
T_LO, T_HI = 1.0, 13.7


@pytest.fixture(scope="module")
def splines():
    """Three smooth, non-degenerate centre tracks, quintic like FIRE's."""
    t = np.linspace(T_LO, T_HI, 60)
    return [make_interp_spline(t, 30.0 * np.sin(0.4 * t + k) + 2.0 * t, k=5)
            for k in range(3)]


@pytest.fixture(scope="module")
def rotation():
    return np.linalg.qr(np.random.default_rng(1).normal(size=(3, 3)))[0]


