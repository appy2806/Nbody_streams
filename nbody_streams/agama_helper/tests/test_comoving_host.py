def test_table_matches_the_closed_form(splines, rotation):
    """-u_dot = -(a x'' / K^2 + a H x' / K) R^T, row by row."""
    tab = center_acceleration_table(splines, rotation, COSMO, n_samples=401)
    assert tab.shape == (401, 4)

    t = tab[:, 0]
    a = COSMO.scale_factor(t)
    H = COSMO.hubble_parameter(a=a)
    d1 = np.column_stack([sp.derivative(1)(t) for sp in splines])
    d2 = np.column_stack([sp.derivative(2)(t) for sp in splines])
    K = KPC_PER_GYR_PER_KMS
    ref = -((a[:, None] * d2 / K ** 2 + (a * H)[:, None] * d1 / K) @ rotation.T)
    assert np.allclose(tab[:, 1:], ref, rtol=0, atol=1e-14)


def test_unit_conversion_divides_by_k_squared():
    """A hand-computable case, in the static background where a = 1 and H = 0.

    Only the ``x_com''/K^2`` term survives, so a centre track with a known
    constant acceleration in kpc/Gyr^2 pins the conversion exactly.  Multiplying
    by ``K^2`` instead is wrong by 9.4 percent -- plausible enough to go
    unnoticed, large enough to matter.
    """
    accel = 3.0                                    # kpc/Gyr^2, x component only
    t = np.linspace(1.0, 13.0, 40)
    sp = [make_interp_spline(t, 0.5 * accel * t ** 2, k=3),
          make_interp_spline(t, np.zeros_like(t), k=3),
          make_interp_spline(t, np.zeros_like(t), k=3)]

    tab = center_acceleration_table(sp, np.eye(3), FlatLCDM.static(), n_samples=101)
    expected = -accel / KPC_PER_GYR_PER_KMS ** 2   # (km/s)^2/kpc
    assert np.allclose(tab[:, 1], expected, rtol=1e-9)
    assert np.allclose(tab[:, 2:], 0.0, atol=1e-9)
    # The wrong sense of the conversion would sit 9.4 percent away.
    assert abs(expected * KPC_PER_GYR_PER_KMS ** 4 / expected - 1.0) > 0.09


def test_hubble_term_scales_with_a_h():
    """With a straight-line centre track x'' = 0, only ``a H x'/K`` is left."""
    speed = 5.0                                     # kpc/Gyr, x component only
    t = np.linspace(1.0, 13.0, 40)
    sp = [make_interp_spline(t, speed * t, k=3),
          make_interp_spline(t, np.zeros_like(t), k=3),
          make_interp_spline(t, np.zeros_like(t), k=3)]

    tab = center_acceleration_table(sp, np.eye(3), COSMO, n_samples=101)
    a = COSMO.scale_factor(tab[:, 0])
    H = COSMO.hubble_parameter(a=a)
    assert np.allclose(tab[:, 1], -a * H * speed / KPC_PER_GYR_PER_KMS, rtol=1e-9)


def test_table_honours_rotation(splines):
    """The identity rotation leaves the components in the simulation frame."""
    eye = center_acceleration_table(splines, np.eye(3), COSMO, n_samples=101)
    rot = np.linalg.qr(np.random.default_rng(7).normal(size=(3, 3)))[0]
    got = center_acceleration_table(splines, rot, COSMO, n_samples=101)
    assert np.allclose(got[:, 1:], eye[:, 1:] @ rot.T)


def test_table_accepts_a_path_pattern(tmp_path, splines, rotation):
    pattern = str(tmp_path / "cen_{}.txt")
    write_center_splines(pattern, splines)
    from_pattern = center_acceleration_table(pattern, rotation, COSMO, n_samples=201)
    from_objects = center_acceleration_table(splines, rotation, COSMO, n_samples=201)
    assert np.allclose(from_pattern, from_objects)


def test_default_t_range_is_the_knot_range(splines, rotation):
    tab = center_acceleration_table(splines, rotation, COSMO)
    assert tab.shape == (1201, 4)
    assert tab[0, 0] == pytest.approx(T_LO)
    assert tab[-1, 0] == pytest.approx(T_HI)


def test_t_range_is_not_clipped_to_the_knots(splines, rotation):
    """FIRE centre splines stop 4.4 Myr short of snapshot 600; the table must
    still be allowed to reach the present day by extrapolation."""
    tab = center_acceleration_table(splines, rotation, COSMO,
                                    t_range=(T_LO, T_HI + 0.05), n_samples=101)
    assert tab[-1, 0] == pytest.approx(T_HI + 0.05)
    assert np.all(np.isfinite(tab))


def test_table_validation(splines, rotation):
    with pytest.raises(ValueError, match=r"\(3, 3\)"):
        center_acceleration_table(splines, np.eye(2), COSMO)
    with pytest.raises(ValueError, match="empty"):
        center_acceleration_table(splines, rotation, COSMO, t_range=(5.0, 5.0))
    with pytest.raises(ValueError, match="n_samples"):
        center_acceleration_table(splines, rotation, COSMO, n_samples=1)


