def test_center_acceleration_force_matches_the_table(splines, rotation):
    """UniformAcceleration force is +a(t), independent of position."""
    tab = center_acceleration_table(splines, rotation, COSMO, n_samples=401)
    pot = center_acceleration(splines, rotation, COSMO, n_samples=401)

    xyz = np.array([[8.0, 1.0, -2.0], [50.0, -30.0, 10.0], [0.0, 0.0, 0.0]])
    i = 200
    force = np.atleast_2d(pot.force(xyz, t=tab[i, 0]))
    assert np.allclose(force, tab[i, 1:], rtol=1e-10, atol=1e-12)
    assert np.allclose(force[0], force[-1])          # spatially uniform


def test_written_table_and_ini_reproduce_the_potential(tmp_path, splines, rotation):
    path = tmp_path / "accCEN.txt"
    written = write_center_acceleration(path, splines, rotation, COSMO, n_samples=401)
    assert written == str(path)

    ini = path.with_suffix(".ini")
    assert "UniformAcceleration" in ini.read_text()

    direct = center_acceleration(splines, rotation, COSMO, n_samples=401)
    from_ini = agama.Potential(str(ini))
    from_file = agama.Potential(type="UniformAcceleration", file=str(path))

    xyz = np.array([[8.0, 1.0, -2.0], [50.0, -30.0, 10.0]])
    for t in (2.0, 7.0, 13.0):
        ref = np.atleast_2d(direct.force(xyz, t=t))
        assert np.allclose(np.atleast_2d(from_ini.force(xyz, t=t)), ref)
        assert np.allclose(np.atleast_2d(from_file.force(xyz, t=t)), ref)


def test_write_center_acceleration_can_skip_the_ini(tmp_path, splines, rotation):
    path = tmp_path / "accCEN.txt"
    write_center_acceleration(path, splines, rotation, COSMO, n_samples=51, ini=False)
    assert path.exists()
    assert not path.with_suffix(".ini").exists()


def test_gpu_matches_cpu(splines, rotation):
    """Both sides use Agama's regularized natural cubic spline on the table."""
    cp = pytest.importorskip("cupy")

    cpu = center_acceleration(splines, rotation, COSMO, n_samples=401)
    gpu = center_acceleration(splines, rotation, COSMO, n_samples=401, gpu=True)

    xyz = np.array([[8.0, 1.0, -2.0], [50.0, -30.0, 10.0]])
    for t in (2.0, 7.0, 13.0):
        got = np.atleast_2d(cp.asnumpy(gpu.force(xyz, t=t)))
        assert np.allclose(got, np.atleast_2d(cpu.force(xyz, t=t)), rtol=1e-12, atol=1e-14)


