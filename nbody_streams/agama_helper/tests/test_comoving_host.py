def test_center_spline_text_round_trip_is_exact(tmp_path, splines):
    """The .txt form must rebuild the same BSpline, derivatives included."""
    pattern = str(tmp_path / "cen_{}.txt")
    written = write_center_splines(pattern, splines)
    assert [p.rsplit("_", 1)[1] for p in written] == ["x.txt", "y.txt", "z.txt"]

    back = read_center_splines(pattern)
    tq = np.linspace(T_LO + 0.5, T_HI - 0.5, 97)
    for orig, new in zip(splines, back):
        assert new.k == orig.k
        assert np.array_equal(new.t, orig.t)
        assert np.array_equal(new(tq), orig(tq))
        assert np.array_equal(new.derivative(2)(tq), orig.derivative(2)(tq))


def test_write_center_splines_rejects_wrong_count(tmp_path, splines):
    with pytest.raises(ValueError, match="expected 3"):
        write_center_splines(str(tmp_path / "cen_{}.txt"), splines[:2])


def test_read_center_splines_reports_missing_and_headerless(tmp_path, splines):
    with pytest.raises(FileNotFoundError):
        read_center_splines(str(tmp_path / "absent_{}.txt"))
    for c in "xyz":
        (tmp_path / f"bad_{c}.txt").write_text("1 2\n3 4\n")
    with pytest.raises(ValueError, match="degree"):
        read_center_splines(str(tmp_path / "bad_{}.txt"))


